package netstack

import circt.stage.ChiselStage
import java.nio.file.{Files, Paths}

object Emit extends App {
    require(args.length >= 1 && args.length <= 2, "usage: netstack.Emit OUTPUT_DIRECTORY [hybrid|bram|auto]")
    MemoryExport.profile = if (args.length == 2) args(1) else "hybrid"
    require(MemoryExport.profiles(MemoryExport.profile), "unsupported memory profile")
    val out = Paths.get(args(0))
    Files.createDirectories(out)
    Files.writeString(out.resolve("SharedTcpReceiveHarness.fir"), ChiselStage.emitCHIRRTL(new SharedTcpReceiveHarness))
    Files.writeString(out.resolve("MemoryQueueHarness.fir"), ChiselStage.emitCHIRRTL(new MemoryQueueHarness))
    MemoryExport.emit(new MemoryQueueHarness, Array("--target-dir", out.resolve("memory-queue-rtl").toString))
    Files.writeString(out.resolve("TcpSackSnapshotHarness.fir"), ChiselStage.emitCHIRRTL(new TcpSackSnapshotHarness))
    Files.writeString(out.resolve("TcpGenerationHarness.fir"), ChiselStage.emitCHIRRTL(new TcpGenerationHarness))
    Files.writeString(out.resolve("NetworkErrorsHarness.fir"), ChiselStage.emitCHIRRTL(new NetworkErrorsHarness))
    Files.writeString(out.resolve("IcmpErrorsHarness.fir"), ChiselStage.emitCHIRRTL(new IcmpErrorsHarness))
    Files.writeString(out.resolve("TcpClosedHarness.fir"), ChiselStage.emitCHIRRTL(new TcpClosedHarness))
    Files.writeString(out.resolve("TcpPmtuHarness.fir"), ChiselStage.emitCHIRRTL(new TcpPmtuHarness))
    Files.writeString(out.resolve("ChecksumHarness.fir"), ChiselStage.emitCHIRRTL(new ChecksumHarness))
    MemoryExport.emit(new ChecksumHarness, Array("--target-dir", args(0)))
    Files.writeString(out.resolve("UdpHarness.fir"), ChiselStage.emitCHIRRTL(new UdpHarness))
    MemoryExport.emit(new UdpHarness, Array("--target-dir", args(0)))
    Files.writeString(out.resolve("BufferHarness.fir"), ChiselStage.emitCHIRRTL(new BufferHarness))
    MemoryExport.emit(new BufferHarness, Array("--target-dir", args(0)))
    Files.writeString(out.resolve("ReceiveHarness.fir"), ChiselStage.emitCHIRRTL(new ReceiveHarness))
    MemoryExport.emit(new ReceiveHarness, Array("--target-dir", args(0)))
    Files.writeString(out.resolve("SliceHarness.fir"), ChiselStage.emitCHIRRTL(new SliceHarness))
    MemoryExport.emit(new SliceHarness, Array("--target-dir", out.resolve("slice-rtl").toString))
    Files.writeString(out.resolve("IpReceiveHarness.fir"), ChiselStage.emitCHIRRTL(new IpReceiveHarness))
    MemoryExport.emit(new IpReceiveHarness, Array("--target-dir", out.resolve("ip-receive-rtl").toString))
    Files.writeString(out.resolve("TransmitHarness.fir"), ChiselStage.emitCHIRRTL(new TransmitHarness))
    MemoryExport.emit(new TransmitHarness, Array("--target-dir", out.resolve("transmit-rtl").toString))
    Files.writeString(out.resolve("ArpHarness.fir"), ChiselStage.emitCHIRRTL(new ArpHarness))
    MemoryExport.emit(new ArpHarness, Array("--target-dir", out.resolve("arp-test-rtl").toString))
    Files.writeString(out.resolve("EthernetHarness.fir"), ChiselStage.emitCHIRRTL(new EthernetHarness))
    MemoryExport.emit(new EthernetHarness, Array("--target-dir", out.resolve("ethernet-test-rtl").toString))
    Files.writeString(out.resolve("TcpReceiveHarness.fir"), ChiselStage.emitCHIRRTL(new TcpReceiveHarness))
    MemoryExport.emit(new TcpReceiveHarness, Array("--target-dir", out.resolve("tcp-receive-test-rtl").toString))
    Files.writeString(out.resolve("TcpTransmitHarness.fir"), ChiselStage.emitCHIRRTL(new TcpTransmitHarness))
    MemoryExport.emit(new TcpTransmitHarness, Array("--target-dir", out.resolve("tcp-transmit-test-rtl").toString))
    Files.writeString(out.resolve("TcpTimerHarness.fir"), ChiselStage.emitCHIRRTL(new TcpTimerHarness))
    MemoryExport.emit(new TcpTimerHarness, Array("--target-dir", out.resolve("tcp-timer-test-rtl").toString))
    Files.writeString(out.resolve("TcpStoreHarness.fir"), ChiselStage.emitCHIRRTL(new TcpStoreHarness))
    MemoryExport.emit(new TcpStoreHarness, Array("--target-dir", out.resolve("tcp-store-test-rtl").toString))
    Files.writeString(out.resolve("TcpControlHarness.fir"), ChiselStage.emitCHIRRTL(new TcpControlHarness))
    MemoryExport.emit(new TcpControlHarness, Array("--target-dir", out.resolve("tcp-control-test-rtl").toString))
    MemoryExport.emit(new TcpConnectionControl(), Array("--target-dir", out.resolve("tcp-control-rtl").toString))
    Files.writeString(out.resolve("TcpManagedHarness.fir"), ChiselStage.emitCHIRRTL(new TcpManagedHarness))
    MemoryExport.emit(new TcpManagedHarness, Array("--target-dir", out.resolve("tcp-managed-test-rtl").toString))
    MemoryExport.emit(new TcpManagedConnection(), Array("--target-dir", out.resolve("tcp-managed-rtl").toString))
    Files.writeString(out.resolve("TcpDataHarness.fir"), ChiselStage.emitCHIRRTL(new TcpDataHarness))
    Files.writeString(out.resolve("TcpHeaderSnapshotHarness.fir"), ChiselStage.emitCHIRRTL(new TcpHeaderSnapshotHarness))
    MemoryExport.emit(new TcpDataHarness, Array("--target-dir", out.resolve("tcp-data-test-rtl").toString))
    MemoryExport.emit(new TcpDataTransmit(), Array("--target-dir", out.resolve("tcp-data-rtl").toString))
    Files.writeString(out.resolve("TcpConnectionTxHarness.fir"), ChiselStage.emitCHIRRTL(new TcpConnectionTxHarness))
    MemoryExport.emit(new TcpConnectionTransmit(), Array("--target-dir", out.resolve("tcp-connection-tx-rtl").toString))
    Files.writeString(out.resolve("TcpRingHarness.fir"), ChiselStage.emitCHIRRTL(new TcpRingHarness))
    MemoryExport.emit(new TcpReceiveRing(), Array("--target-dir", out.resolve("tcp-ring-rtl").toString))
    Files.writeString(out.resolve("TcpEndpointHarness.fir"), ChiselStage.emitCHIRRTL(new TcpEndpointHarness))
    MemoryExport.emit(new TcpIpv4Endpoint(), Array("--target-dir", out.resolve("tcp-endpoint-rtl").toString))
    MemoryExport.emit(new EthernetTcpUdpEndpoint(), Array("--target-dir", out.resolve("ethernet-tcp-udp-rtl").toString))
    MemoryExport.emit(new MultiTcpIpv4Endpoint(), Array("--target-dir", out.resolve("multi-tcp-endpoint-rtl").toString))
    MemoryExport.emit(new MultiEthernetTcpUdpEndpoint(), Array("--target-dir", out.resolve("multi-ethernet-tcp-udp-rtl").toString))
    Files.writeString(out.resolve("MultiTcpEndpointHarness.fir"), ChiselStage.emitCHIRRTL(new MultiTcpEndpointHarness))
    Files.writeString(out.resolve("MultiEthernetPortHarness.fir"), ChiselStage.emitCHIRRTL(new MultiEthernetPortHarness))
    Files.writeString(out.resolve("MultiEthernetTcpHarness.fir"), ChiselStage.emitCHIRRTL(new MultiEthernetTcpHarness))
    Files.writeString(out.resolve("EthernetTcpHarness.fir"), ChiselStage.emitCHIRRTL(new EthernetTcpHarness))
    Files.writeString(out.resolve("TcpCongestionHarness.fir"), ChiselStage.emitCHIRRTL(new TcpCongestionHarness))
    Files.writeString(out.resolve("TcpCongestedEndpointHarness.fir"), ChiselStage.emitCHIRRTL(new TcpCongestedEndpointHarness))
    Files.writeString(out.resolve("EthernetServiceHarness.fir"), ChiselStage.emitCHIRRTL(new EthernetServiceHarness))
    Files.writeString(out.resolve("TcpPipelinedTimerHarness.fir"), ChiselStage.emitCHIRRTL(new TcpPipelinedTimerHarness))
    // Production geometry is emitted separately: shared submodule names must
    // never overwrite the reduced-depth simulation instances above.
    val rtl = out.resolve("rtl")
    Files.createDirectories(rtl)
    MemoryExport.emit(new UdpReceive(), Array("--target-dir", rtl.toString))
    MemoryExport.emit(new Ipv4UdpReceive(), Array("--target-dir", out.resolve("ipv4-rtl").toString))
    MemoryExport.emit(new Ipv4UdpTransmit(), Array("--target-dir", out.resolve("ipv4-tx-rtl").toString))
    MemoryExport.emit(new ArpEndpoint(), Array("--target-dir", out.resolve("arp-rtl").toString))
    MemoryExport.emit(new EthernetUdpEndpoint(), Array("--target-dir", out.resolve("ethernet-rtl").toString))
    MemoryExport.emit(new TcpReceive(), Array("--target-dir", out.resolve("tcp-receive-rtl").toString))
    MemoryExport.emit(new Ipv4TcpTransmit(), Array("--target-dir", out.resolve("tcp-transmit-rtl").toString))
    MemoryExport.emit(new TcpRetransmissionTimer(), Array("--target-dir", out.resolve("tcp-timer-rtl").toString))
    MemoryExport.emit(new TcpPayloadStore(), Array("--target-dir", out.resolve("tcp-store-rtl").toString))
}
