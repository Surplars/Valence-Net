    val io = IO(new Bundle {
        val rxSackPermitted = Input(Bool())
        val sackCount = Input(UInt(3.W))
        val sackLeft0 = Input(UInt(32.W))
        val sackLeft1 = Input(UInt(32.W))
        val sackLeft2 = Input(UInt(32.W))
        val sackLeft3 = Input(UInt(32.W))
        val sackRight0 = Input(UInt(32.W))
        val sackRight1 = Input(UInt(32.W))
        val sackRight2 = Input(UInt(32.W))
        val sackRight3 = Input(UInt(32.W))
        val sackEnabled = Output(Bool())
        val dataOptionLength = Output(UInt(6.W))
        val generationGap = Output(Bool())
        val invariantFailure = Output(Bool())
        val referenceFailure = Output(Bool())
        val ackGap = Output(Bool())
        val countGap = Output(Bool())
        val openValid = Input(Bool())
        val passive = Input(Bool())
        val localIp = Input(UInt(32.W))
        val remoteIp = Input(UInt(32.W))
        val localPort = Input(UInt(16.W))
        val remotePort = Input(UInt(16.W))
        val initialSequence = Input(UInt(32.W))
        val localMss = Input(UInt(16.W))
        val offerScale = Input(Bool())
        val localScale = Input(UInt(4.W))
        val passiveInitialSequence = Input(UInt(32.W))
        val closeValid = Input(Bool())
        val abort = Input(Bool())
        val rxValid = Input(Bool())
        val rxSourceIp = Input(UInt(32.W))
        val rxDestinationIp = Input(UInt(32.W))
        val rxSourcePort = Input(UInt(16.W))
        val rxDestinationPort = Input(UInt(16.W))
        val rxSequence = Input(UInt(32.W))
        val rxAcknowledgement = Input(UInt(32.W))
        val rxFlags = Input(UInt(8.W))
        val rxWindow = Input(UInt(16.W))
        val rxLength = Input(UInt(16.W))
        val rxErrors = Input(UInt(4.W))
        val rxUrgent = Input(UInt(16.W))
        val rxMssPresent = Input(Bool())
        val rxMss = Input(UInt(16.W))
        val rxScalePresent = Input(Bool())
        val rxScale = Input(UInt(4.W))
        val payloadToken = Input(UInt(32.W))
        val payloadStored = Input(Bool())
        val dispositionReady = Input(Bool())
        val controlReady = Input(Bool())
        val ackReady = Input(Bool())
        val noticeReady = Input(Bool())
        val reserveValid = Input(Bool())
        val reserveLength = Input(UInt(16.W))
        val completedValid = Input(Bool())
        val completedGeneration = Input(UInt(32.W))
        val completedEnd = Input(UInt(32.W))
        val completedRetransmission = Input(Bool())
        val retryValid = Input(Bool())
        val retryGeneration = Input(UInt(32.W))
        val replayReady = Input(Bool())
        val receiveWindow = Input(UInt(32.W))
        val congestionWindow = Input(UInt(32.W))
        val tick = Input(Bool())
        val updateWindow = Input(Bool())
        val openReady = Output(Bool())
        val closeReady = Output(Bool())
        val rxReady = Output(Bool())
        val reserveReady = Output(Bool())
        val sendSequence = Output(UInt(32.W))
        val retryReady = Output(Bool())
        val replayValid = Output(Bool())
        val replaySequence = Output(UInt(32.W))
        val completionAccepted = Output(Bool())
        val invalidCompletion = Output(Bool())
        val state = Output(UInt(4.W))
        val generation = Output(UInt(32.W))
        val sendOldest = Output(UInt(32.W))
        val sendNext = Output(UInt(32.W))
        val sendActual = Output(UInt(32.W))
        val receiveNext = Output(UInt(32.W))
        val sendWindow = Output(UInt(32.W))
        val sendMss = Output(UInt(16.W))
        val peerScale = Output(UInt(4.W))
        val scaleEnabled = Output(Bool())
        val controlValid = Output(Bool())
        val controlGeneration = Output(UInt(32.W))
        val controlRetransmission = Output(Bool())
        val controlSequenceSpace = Output(Bool())
        val txSourceIp = Output(UInt(32.W))
        val txDestinationIp = Output(UInt(32.W))
        val txSourcePort = Output(UInt(16.W))
        val txDestinationPort = Output(UInt(16.W))
        val txSequence = Output(UInt(32.W))
        val txAcknowledgement = Output(UInt(32.W))
        val txFlags = Output(UInt(8.W))
        val txWindow = Output(UInt(16.W))
        val txOptionLength = Output(UInt(6.W))
        val txOptions = Output(UInt(64.W))
        val dispositionValid = Output(Bool())
        val dispositionGeneration = Output(UInt(32.W))
        val dispositionToken = Output(UInt(32.W))
        val dispositionKeep = Output(Bool())
        val dispositionSkip = Output(UInt(16.W))
        val dispositionLength = Output(UInt(16.W))
        val dispositionFin = Output(Bool())
        val dispositionBeforeEstablished = Output(Bool())
        val dispositionUrgent = Output(Bool())
        val dispositionUrgentSequence = Output(UInt(32.W))
        val ackValid = Output(Bool())
        val ackGeneration = Output(UInt(32.W))
        val ackPrevious = Output(UInt(32.W))
        val ackAcknowledgement = Output(UInt(32.W))
        val ackWindow = Output(UInt(32.W))
        val ackDuplicate = Output(Bool())
        val ackWindowChanged = Output(Bool())
        val ackHandshake = Output(Bool())
        val noticeValid = Output(Bool())
        val noticeGeneration = Output(UInt(32.W))
        val noticeFlags = Output(UInt(5.W))
    })
    val dut = Module(new TcpConnectionControl(24, 4, sackSupport = true))
    dut.io.rx.bits.segment := 0.U.asTypeOf(new TcpSegment)
    dut.io.open.valid := io.openValid
    dut.io.open.bits.passive := io.passive
    dut.io.open.bits.localIp := io.localIp
    dut.io.open.bits.remoteIp := io.remoteIp
    dut.io.open.bits.localPort := io.localPort
    dut.io.open.bits.remotePort := io.remotePort
    dut.io.open.bits.initialSequence := io.initialSequence
    dut.io.open.bits.localMss := io.localMss
    dut.io.open.bits.offerScale := io.offerScale
    dut.io.open.bits.localScale := io.localScale
    dut.io.passiveInitialSequence := io.passiveInitialSequence
    dut.io.pathMtuLimit := 65535.U
    dut.io.pathMtuUpdate.valid := false.B
    dut.io.pathMtuUpdate.bits := 0.U.asTypeOf(new TcpPathMtuUpdate)
    dut.io.close.valid := io.closeValid
    dut.io.close.bits := io.abort
    dut.io.rx.valid := io.rxValid
    dut.io.rx.bits.segment.sourceIp := io.rxSourceIp
    dut.io.rx.bits.segment.destinationIp := io.rxDestinationIp
    dut.io.rx.bits.segment.sourcePort := io.rxSourcePort
    dut.io.rx.bits.segment.destinationPort := io.rxDestinationPort
    dut.io.rx.bits.segment.sequence := io.rxSequence
    dut.io.rx.bits.segment.acknowledgement := io.rxAcknowledgement
    dut.io.rx.bits.segment.flags := io.rxFlags
    dut.io.rx.bits.segment.window := io.rxWindow
    dut.io.rx.bits.segment.payloadLength := io.rxLength
    dut.io.rx.bits.segment.errors := io.rxErrors
    dut.io.rx.bits.segment.urgent := io.rxUrgent
    dut.io.rx.bits.segment.options.mssPresent := io.rxMssPresent
    dut.io.rx.bits.segment.options.mss := io.rxMss
    dut.io.rx.bits.segment.options.scalePresent := io.rxScalePresent
    dut.io.rx.bits.segment.options.scale := io.rxScale
    dut.io.rx.bits.segment.options.sackPermitted := io.rxSackPermitted
    dut.io.rx.bits.payloadToken := io.payloadToken
    dut.io.rx.bits.payloadStored := io.payloadStored
    dut.io.rx.bits.reassembled := false.B; dut.io.rx.bits.replayGeneration := 0.U
    dut.io.disposition.ready := io.dispositionReady
    dut.io.control.ready := io.controlReady
    dut.io.ack.ready := io.ackReady
    dut.io.notice.ready := io.noticeReady
    dut.io.sendReserve.valid := io.reserveValid
    dut.io.sendReserve.bits := io.reserveLength
    dut.io.completed.valid := io.completedValid
    dut.io.completed.bits.generation := io.completedGeneration
    dut.io.completed.bits.endSequence := io.completedEnd
    dut.io.completed.bits.retransmission := io.completedRetransmission
    dut.io.completed.bits.timeoutRetry := io.completedRetransmission
    dut.io.retry.valid := io.retryValid
    dut.io.retry.bits := io.retryGeneration
    dut.io.replay.ready := io.replayReady
    dut.io.receiveWindow := io.receiveWindow
    dut.io.congestionWindow := io.congestionWindow
    dut.io.probe.valid := false.B; dut.io.probe.bits := true.B
    dut.io.tick := io.tick
    dut.io.updateWindow := io.updateWindow
    dut.io.receiveSack.count := io.sackCount
    dut.io.receiveSack.left := VecInit(io.sackLeft0, io.sackLeft1, io.sackLeft2, io.sackLeft3)
    dut.io.receiveSack.right := VecInit(io.sackRight0, io.sackRight1, io.sackRight2, io.sackRight3)
    // Reference reproduces the original cached-generation compatibility guard.
    // This oracle remains outside the production module and observes every cycle.
    val (referenceNextLength, referenceNextOptions) = TcpSackEncoding(
        dut.io.receiveSack, dut.io.receiveNext, dut.io.sackEnabled)
    val referenceLength = RegNext(referenceNextLength, 0.U)
    val referenceOptions = RegNext(referenceNextOptions)
    val referenceAck = RegNext(dut.io.receiveNext, 0.U(32.W))
    val referenceGeneration = RegNext(dut.io.generation, 0.U(32.W))
    val referenceCount = RegNext(io.sackCount, 0.U(3.W))
    val referenceCompatible = dut.io.sackEnabled && io.sackCount =/= 0.U &&
        referenceAck === dut.io.receiveNext && referenceGeneration === dut.io.generation &&
        referenceCount === io.sackCount
    val referenceOptionLength = Mux(referenceCompatible && dut.io.sendMss > referenceLength,
        referenceLength, 0.U)
    io.sackEnabled := dut.io.sackEnabled
    io.dataOptionLength := dut.io.dataHeader.optionLength
    io.generationGap := referenceGeneration =/= dut.io.generation
    io.invariantFailure := dut.io.sackEnabled && io.generationGap
    io.referenceFailure := dut.io.dataHeader.optionLength =/= referenceOptionLength ||
        referenceOptionLength =/= 0.U && dut.io.dataHeader.options =/= referenceOptions
    io.ackGap := referenceAck =/= dut.io.receiveNext
    io.countGap := referenceCount =/= io.sackCount
    io.openReady := dut.io.open.ready
    io.closeReady := dut.io.close.ready
    io.rxReady := dut.io.rx.ready
    io.reserveReady := dut.io.sendReserve.ready
    io.sendSequence := dut.io.sendSequence
    io.retryReady := dut.io.retry.ready
    io.replayValid := dut.io.replay.valid
    io.replaySequence := dut.io.replay.bits
    io.completionAccepted := dut.io.completionAccepted
    io.invalidCompletion := dut.io.invalidCompletion
    io.state := dut.io.state
    io.generation := dut.io.generation
    io.sendOldest := dut.io.sendOldest
    io.sendNext := dut.io.sendNext
    io.sendActual := dut.io.sendActual
    io.receiveNext := dut.io.receiveNext
    io.sendWindow := dut.io.sendWindow
    io.sendMss := dut.io.sendMss
    io.peerScale := dut.io.peerScale
    io.scaleEnabled := dut.io.scaleEnabled
    io.controlValid := dut.io.control.valid
    io.controlGeneration := dut.io.control.bits.generation
    io.controlRetransmission := dut.io.control.bits.retransmission
    io.controlSequenceSpace := dut.io.control.bits.sequenceSpace
    io.txSourceIp := dut.io.control.bits.command.sourceIp
    io.txDestinationIp := dut.io.control.bits.command.destinationIp
    io.txSourcePort := dut.io.control.bits.command.sourcePort
    io.txDestinationPort := dut.io.control.bits.command.destinationPort
    io.txSequence := dut.io.control.bits.command.sequence
    io.txAcknowledgement := dut.io.control.bits.command.acknowledgement
    io.txFlags := dut.io.control.bits.command.flags
    io.txWindow := dut.io.control.bits.command.window
    io.txOptionLength := dut.io.control.bits.command.optionLength
    io.txOptions := dut.io.control.bits.command.options(63, 0)
    io.dispositionValid := dut.io.disposition.valid
    io.dispositionGeneration := dut.io.disposition.bits.generation
    io.dispositionToken := dut.io.disposition.bits.token
    io.dispositionKeep := dut.io.disposition.bits.keep
    io.dispositionSkip := dut.io.disposition.bits.skip
    io.dispositionLength := dut.io.disposition.bits.length
    io.dispositionFin := dut.io.disposition.bits.fin
    io.dispositionBeforeEstablished := dut.io.disposition.bits.beforeEstablished
    io.dispositionUrgent := dut.io.disposition.bits.urgent
    io.dispositionUrgentSequence := dut.io.disposition.bits.urgentSequence
    io.ackValid := dut.io.ack.valid
    io.ackGeneration := dut.io.ack.bits.generation
    io.ackPrevious := dut.io.ack.bits.previous
    io.ackAcknowledgement := dut.io.ack.bits.acknowledgement
    io.ackWindow := dut.io.ack.bits.window
    io.ackDuplicate := dut.io.ack.bits.duplicate
    io.ackWindowChanged := dut.io.ack.bits.windowChanged
    io.ackHandshake := dut.io.ack.bits.handshake
    io.noticeValid := dut.io.notice.valid
    io.noticeGeneration := dut.io.notice.bits.generation
    io.noticeFlags := dut.io.notice.bits.flags
}
