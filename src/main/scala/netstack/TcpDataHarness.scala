package netstack

import chisel3._
import chisel3.util._

class TcpDataHarness extends Module {
    val io = IO(new Bundle {
        val allocateValid = Input(Bool())
        val length = Input(UInt(16.W))
        val context = Input(UInt(64.W))
        val valid = Input(Bool())
        val lo = Input(UInt(64.W))
        val hi = Input(UInt(64.W))
        val keep = Input(UInt(16.W))
        val last = Input(Bool())
        val error = Input(Bool())
        val storedReady = Input(Bool())
        val enabled = Input(Bool())
        val generation = Input(UInt(32.W))
        val sendOldest = Input(UInt(32.W))
        val sendActual = Input(UInt(32.W))
        val sendSequence = Input(UInt(32.W))
        val credit = Input(UInt(32.W))
        val mss = Input(UInt(16.W))
        val reserveReady = Input(Bool())
        val replayValid = Input(Bool())
        val replaySequence = Input(UInt(32.W))
        val outReady = Input(Bool())
        val sourceIp = Input(UInt(32.W))
        val destinationIp = Input(UInt(32.W))
        val sourcePort = Input(UInt(16.W))
        val destinationPort = Input(UInt(16.W))
        val acknowledgement = Input(UInt(32.W))
        val window = Input(UInt(16.W))
        val ttl = Input(UInt(8.W))
        val tos = Input(UInt(8.W))
        val allocateReady = Output(Bool())
        val ready = Output(Bool())
        val storedValid = Output(Bool())
        val storedToken = Output(UInt(32.W))
        val storedLength = Output(UInt(16.W))
        val storedContext = Output(UInt(64.W))
        val storedError = Output(Bool())
        val reserveValid = Output(Bool())
        val reserveLength = Output(UInt(16.W))
        val replayReady = Output(Bool())
        val replayMiss = Output(Bool())
        val outValid = Output(Bool())
        val outLo = Output(UInt(64.W))
        val outHi = Output(UInt(64.W))
        val outKeep = Output(UInt(16.W))
        val outLast = Output(Bool())
        val outError = Output(Bool())
        val preparedValid = Output(Bool())
        val freeBanks = Output(UInt(3.W))
        val fault = Output(Bool())
        val packetGeneration = Output(UInt(32.W))
        val packetSequence = Output(UInt(32.W))
        val packetLength = Output(UInt(16.W))
        val packetContext = Output(UInt(64.W))
        val packetRetransmission = Output(Bool())
        val packetPush = Output(Bool())
        val preparedGeneration = Output(UInt(32.W))
        val preparedSequence = Output(UInt(32.W))
        val preparedLength = Output(UInt(16.W))
        val preparedContext = Output(UInt(64.W))
        val preparedRetransmission = Output(Bool())
        val preparedPush = Output(Bool())
    })
    val dut = Module(new TcpDataTransmit(4, 128))
    dut.io.allocate.valid := io.allocateValid
    dut.io.allocate.bits.length := io.length
    dut.io.allocate.bits.context := io.context
    dut.io.in.valid := io.valid
    dut.io.in.bits.keep := io.keep
    dut.io.in.bits.last := io.last
    dut.io.in.bits.error := io.error
    dut.io.stored.ready := io.storedReady
    dut.io.reserve.ready := io.reserveReady
    dut.io.replay.valid := io.replayValid
    dut.io.replay.bits := io.replaySequence
    dut.io.out.ready := io.outReady
    dut.io.enabled := io.enabled
    dut.io.generation := io.generation
    dut.io.sendOldest := io.sendOldest
    dut.io.sendActual := io.sendActual
    dut.io.sendSequence := io.sendSequence
    dut.io.credit := io.credit
    dut.io.mss := io.mss
    dut.io.header.sourceIp := io.sourceIp
    dut.io.header.destinationIp := io.destinationIp
    dut.io.header.sourcePort := io.sourcePort
    dut.io.header.destinationPort := io.destinationPort
    dut.io.header.acknowledgement := io.acknowledgement
    dut.io.header.window := io.window
    dut.io.header.ttl := io.ttl
    dut.io.header.tos := io.tos
    dut.io.in.bits.data := Cat(io.hi, io.lo)
    io.allocateReady := dut.io.allocate.ready
    io.ready := dut.io.in.ready
    io.storedValid := dut.io.stored.valid
    io.storedToken := dut.io.stored.bits.token
    io.storedLength := dut.io.stored.bits.length
    io.storedContext := dut.io.stored.bits.context
    io.storedError := dut.io.stored.bits.error
    io.reserveValid := dut.io.reserve.valid
    io.reserveLength := dut.io.reserve.bits
    io.replayReady := dut.io.replay.ready
    io.replayMiss := dut.io.replayMiss
    io.outValid := dut.io.out.valid
    io.outLo := dut.io.out.bits.data(63, 0)
    io.outHi := dut.io.out.bits.data(127, 64)
    io.outKeep := dut.io.out.bits.keep
    io.outLast := dut.io.out.bits.last
    io.outError := dut.io.out.bits.error
    io.preparedValid := dut.io.prepared.valid
    io.freeBanks := dut.io.freeBanks
    io.fault := dut.io.fault
    io.packetGeneration := dut.io.packet.generation
    io.packetSequence := dut.io.packet.sequence
    io.packetLength := dut.io.packet.length
    io.packetContext := dut.io.packet.context
    io.packetRetransmission := dut.io.packet.retransmission
    io.packetPush := dut.io.packet.push
    io.preparedGeneration := dut.io.prepared.bits.generation
    io.preparedSequence := dut.io.prepared.bits.sequence
    io.preparedLength := dut.io.prepared.bits.length
    io.preparedContext := dut.io.prepared.bits.context
    io.preparedRetransmission := dut.io.prepared.bits.retransmission
    io.preparedPush := dut.io.prepared.bits.push
}
